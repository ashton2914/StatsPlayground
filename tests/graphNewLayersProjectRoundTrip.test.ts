import assert from "node:assert/strict";
import { useGraphBuilderNewStore as store } from "../src/stores/useGraphBuilderNewStore";
import { useProjectStore } from "../src/stores/useProjectStore";
useProjectStore.setState({ readOnly: false, dirty: false });
store.getState().reset();
const id = store.getState().open("source", 1);
store.getState().setColumns(id, "x", "y");
store.getState().setOverlay(id, "group");
const hidden = `sha256:${"a".repeat(64)}`;
store.getState().setHiddenOverlayGroups(id, [hidden]);
store.getState().setCamera(id, { xMin: 1, xMax: 2, yMin: 3, yMax: 4 });
const points = store.getState().items[0].layers[0];
store.getState().setLayerOptions(id, points.id, { summaryStat: "sum", errorInterval: "stdDev", intervalStyle: "band", jitter: "normal", jitterLimit: 0.8 });
store.getState().addLayer(id, "line");
const line = store.getState().items[0].layers[1];
store.getState().setLayerOptions(id, line.id, { rowOrder: true, connection: "spline", summaryStat: "median", fill: "between", errorInterval: "ci95", intervalStyle: "band", missingFactors: "include", missingValues: "break" });
const saved = JSON.parse(JSON.stringify(store.getState().items));
assert.equal("transportId" in saved[0], false);
assert.equal("showMean" in saved[0], false);
assert.equal("rawMode" in saved[0], false);
store.getState().reset();
useProjectStore.setState({ dirty: false });
store.getState().loadFromProject(saved);
assert.deepEqual(store.getState().items, saved);
assert.equal(useProjectStore.getState().dirty, false);
store.getState().reopen(id, 2);
assert.deepEqual(store.getState().sessions[0].layers, saved[0].layers);
assert.deepEqual(store.getState().items[0].camera, saved[0].camera);
for (const layer of store.getState().items[0].layers) store.getState().removeLayer(id, layer.id);
const empty = JSON.parse(JSON.stringify(store.getState().items));
store.getState().loadFromProject(empty);
assert.deepEqual(store.getState().items[0].layers, []);
console.log("v3 full options, camera, hidden groups and empty layers roundtrip passed");
const snapshot = { items: saved, sessions: [{ ...saved[0], datasetGeneration: 2, transportId: "old", runtimeEpoch: 3 }] };
store.getState().reset();
const { restoreGraphNewHotState } = await import("../src/stores/useGraphBuilderNewStore");
restoreGraphNewHotState(snapshot);
assert.equal(store.getState().sessions[0].id, saved[0].id);
assert.deepEqual(store.getState().sessions[0].layers, saved[0].layers);
assert.notEqual(store.getState().sessions[0].transportId, "old");
