import assert from "node:assert/strict";
import {createProjectHistoryStore} from "../src/stores/useProjectHistoryStore.ts";
import type {ProjectHistoryPage} from "../src/types/projectPersistence.ts";
const row=(id:string)=>({id,datasetId:"table",operation:"cell_delta",applied:true,generation:1});
const pending:Array<{epoch:number;after:string|null;resolve:(value:ProjectHistoryPage)=>void;reject:(error:Error)=>void}>=[];
const store=createProjectHistoryStore({listProjectHistory:(epoch,request)=>{
  assert.equal(request.limit,200);assert.equal(request.datasetId,null);
  return new Promise((resolve,reject)=>pending.push({epoch,after:request.after,resolve,reject}));
}});
store.getState().install(7,1);assert.equal(pending.length,0,"session installation must not fetch history");
const first=store.getState().loadNextPage();const duplicate=store.getState().loadNextPage();
assert.equal(pending.length,1);
pending[0].resolve({items:[row("one")],nextCursor:"next",committedRevision:1});await Promise.all([first,duplicate]);
assert.deepEqual(store.getState().items.map(item=>item.id),["one"]);
const more=store.getState().loadNextPage();assert.equal(pending[1].after,"next");
pending[1].reject(new Error("project_history_cursor_stale"));await Promise.resolve();await Promise.resolve();
assert.equal(pending[2].after,null,"a stale cursor must restart from the first page once");
pending[2].resolve({items:[row("two")],nextCursor:null,committedRevision:2});await more;
assert.deepEqual(store.getState().items.map(item=>item.id),["two"]);
store.getState().install(7,1);assert.equal(store.getState().committedRevision,2,"late session revisions cannot regress a newer page");
store.getState().install(8,0);const old=store.getState().loadNextPage();
store.getState().install(9,0);const current=store.getState().loadNextPage();
pending[3].resolve({items:[row("old")],nextCursor:null,committedRevision:0});await old;
assert.deepEqual(store.getState().items,[]);
pending[4].reject(new Error("read failed"));await current;
assert.match(store.getState().error??"",/read failed/);
const retry=store.getState().loadNextPage();pending[5].resolve({items:[row("current")],nextCursor:null,committedRevision:0});await retry;
assert.deepEqual(store.getState().items.map(item=>item.id),["current"]);
const synchronous=createProjectHistoryStore({listProjectHistory:()=>{throw new Error("synchronous failure");}});
synchronous.getState().install(1,0);await synchronous.getState().loadNextPage();await synchronous.getState().loadNextPage();
assert.equal(synchronous.getState().loading,false);assert.match(synchronous.getState().error??"",/synchronous failure/);
console.log("project history catalog: lazy bounded pages, deduplication, cursor restart, retries and session fences passed");
